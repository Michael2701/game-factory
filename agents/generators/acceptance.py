"""Deterministic acceptance test for a generated game (M21): proves a human can play it.

Written from the GameSpec by code, never by the LLM, and locked for the agents. It uses
REAL input only: a pointer click on the canvas starts the game and real arrow keys move the
player. Test hooks are used only to read state and for deterministic time control
(`skipTime(60)` to reach game over). Screenshots go to test-results/acceptance/.
"""

from agents.schemas import GameSpec

ACCEPTANCE_FILE = "tests/acceptance.spec.ts"
SHOTS_DIR = "test-results/acceptance"
CANVAS_CLICK = (240, 320)  # inside the 480x640 template canvas; StartScene starts on a click anywhere
STILL_MS = 300  # no key held for this long -> playerX must not change (catches fake/animated hooks)
MOVE_TIMEOUT_MS = 3000
ARROWS = {"left": ("ArrowLeft", "<"), "right": ("ArrowRight", ">")}


def arrow_keys(spec: GameSpec) -> list[tuple[str, str]]:
    """(key, comparison) for the horizontal arrow controls the GameSpec names, left first."""
    inputs = " ".join(c.input.lower() for c in spec.controls)
    return [ARROWS[side] for side in ("left", "right") if f"arrow{side}" in inputs.replace(" ", "")]


def acceptance_spec(spec: GameSpec, player_x: str = "__GAME_STATE__.playerX",
                    import_from: str = "@playwright/test") -> str:
    """TypeScript source of tests/acceptance.spec.ts for `spec`.

    `player_x`: expression on `window` that yields the player's x (the hook contract's playerX;
    other projects, e.g. M20 baselines, may expose it differently).
    """
    x = f"(window as any).{player_x}"
    moves = []
    for key, op in arrow_keys(spec):
        moves.append(f"""
  // {key}: real keyboard input must move the player
  const before{key} = await page.evaluate(() => {x});
  await page.keyboard.down('{key}');
  try {{
    await page.waitForFunction((start) => {x} {op} start, before{key}, {{ timeout: {MOVE_TIMEOUT_MS} }});
  }} catch {{
    throw new Error(`{key} did not move the player: {player_x} stayed ${{await page.evaluate(() => {x})}}`);
  }} finally {{
    await page.keyboard.up('{key}');
  }}""")
    return f"""import {{ test, expect }} from '{import_from}';

// Generated by agents/generators/acceptance.py from the GameSpec "{spec.title}" (M21). Locked for the agents.
// Real input only: a pointer click starts the game, real arrow keys move the player.
// Hooks are used only to read state and for time control (skipTime). Screenshots: {SHOTS_DIR}/.

test('acceptance: click to start, move with the arrow keys, reach game over', async ({{ page }}) => {{
  await page.goto('/');
  await page.waitForFunction(() => (window as any).__GAME_STATE__?.scene === 'StartScene');
  await page.screenshot({{ path: '{SHOTS_DIR}/menu.png' }});

  // real pointer input on the canvas (never the startGame test hook)
  await page.locator('canvas').click({{ position: {{ x: {CANVAS_CLICK[0]}, y: {CANVAS_CLICK[1]} }} }});
  await page.waitForFunction(() => (window as any).__GAME_STATE__?.scene === 'GameScene');

  const still = await page.evaluate(() => {x});
  expect(typeof still, '{player_x} must be a number').toBe('number');
  await page.waitForTimeout({STILL_MS});
  expect(await page.evaluate(() => {x}), 'the player moved with no key held').toBe(still);
  await page.screenshot({{ path: '{SHOTS_DIR}/gameplay.png' }});
{"".join(moves)}

  // deterministic time control only: end the round
  await page.evaluate(() => (window as any).__TEST_API__.skipTime(60));
  await page.waitForFunction(() => (window as any).__GAME_STATE__?.scene === 'GameOverScene');
  await page.screenshot({{ path: '{SHOTS_DIR}/gameover.png' }});
}});
"""
